import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, relative } from 'node:path';
import { buildEdges, diffRegions, regionize, TEST_PATH, type FileRegions } from '../src/regions/index.js';
import { ROOT, writeResult } from './lib.js';

const SRC = join(ROOT, 'bench/cache/django-src');
const PATCHES = join(ROOT, 'bench/cache/a_patches_head'); // regenerated by bench/e1/amech.py at django-src HEAD; v1 patches target per-instance base commits
const CACHE = join(ROOT, 'bench/cache/t4'); mkdirSync(CACHE, { recursive: true });
const PY = join(homedir(), 'Documents/loom-v2/bench/.venv/bin/python');
const HOPS = 3;
const sh = (cmd: string, args: string[], cwd = SRC) => execFileSync(cmd, args, { cwd, encoding: 'utf8', maxBuffer: 1 << 28 });

// 1. index django/ + tests/ once (clean tree)
function walk(d: string, out: string[] = []): string[] {
  for (const f of readdirSync(d).sort()) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p, out); else if (f.endsWith('.py')) out.push(p); }
  return out;
}
sh('git', ['checkout', '-q', '--', '.']);
const maps: FileRegions[] = [];
for (const p of [...walk(join(SRC, 'django')), ...walk(join(SRC, 'tests'))]) maps.push(await regionize(relative(SRC, p), readFileSync(p, 'utf8')));
const { edges } = buildEdges(maps.filter((m) => !m.degraded));
const rev = new Map<string, string[]>();
for (const e of edges) if (e.kind === 'CALLS' || e.kind === 'TESTS') (rev.get(e.to) ?? rev.set(e.to, []).get(e.to)!).push(e.from);
const byId = new Map(maps.flatMap((m) => m.regions.map((r) => [r.id, { path: m.path, r }] as const)));
const testIds = (path: string, qprefix: string) => [...byId.values()].filter((x) => x.path === path && x.r.kind === 'definition' && (x.r.qname === qprefix || x.r.qname.startsWith(qprefix + '.')) && /(^|\.)test/.test(x.r.qname)).map((x) => x.r.id);

// 2. failing test ids from runtests output → region ids
function failed(out: string): { ids: Set<string>; crash: boolean } {
  const ids = new Set<string>(); let crash = !/^Ran \d+ tests?/m.test(out);
  for (const m of out.matchAll(/^(?:ERROR|FAIL): (\S+) \(([\w.]+)\)/gm)) {
    const [name, dotted] = [m[1], m[2]];
    const parts = dotted.split('.');
    // try longest module prefix that exists as tests/<a>/<b>.py
    for (let k = parts.length; k > 0; k--) {
      const file = join('tests', ...parts.slice(0, k)) + '.py';
      if (!existsSync(join(SRC, file))) continue;
      const q = parts.slice(k).join('.');
      for (const id of testIds(file, q || (name === 'setUpClass' ? '' : name))) ids.add(id);
      break;
    }
  }
  return { ids, crash };
}

function runSuite(cache: string): string {
  if (!existsSync(cache)) {
    const r = spawnSync(PY, ['tests/runtests.py', '--parallel', '1', '-v', '0'], { cwd: SRC, encoding: 'utf8', env: { ...process.env, PYTHONPATH: SRC }, maxBuffer: 1 << 28 });
    writeFileSync(cache, (r.stdout ?? '') + (r.stderr ?? ''));
  }
  return readFileSync(cache, 'utf8');
}
// baseline on the clean tree: tests that already fail are excluded from every patch's failure set
const baseline = process.env.T4_DRY ? new Set<string>() : failed(runSuite(join(CACHE, '_baseline.txt'))).ids;

const rows: Array<{ patch: string; changed: string[]; failed: number; predicted: number; hit: number; crash: boolean }> = [];
for (const patch of readdirSync(PATCHES).filter((f) => f.endsWith('.patch')).sort()) {
  if (process.env.T4_ONLY && patch !== process.env.T4_ONLY) continue;
  const p = join(PATCHES, patch);
  // definition file: a patched file defining `def <name>(` at module level in the clean tree; when several
  // do (defaultfilters.slugify wraps utils.text.slugify), the one the others import <name> from
  const fname = patch.split('__')[0];
  sh('git', ['checkout', '-q', '--', '.']);   // the definition file is chosen on the clean tree, not the previous patch's
  const files = [...readFileSync(p, 'utf8').matchAll(/^diff --git a\/(django\/\S+\.py)/gm)].map((m) => m[1]);
  const cands = files.filter((f) => new RegExp(`^def ${fname}\\(`, 'm').test(readFileSync(join(SRC, f), 'utf8')));
  const mod = (f: string) => f.replace(/\.py$/, '').replace(/\/__init__$/, '').replaceAll('/', '.');
  const defFile = cands.length === 1 ? cands[0] : cands.find((c) => cands.some((o) => o !== c &&
    new RegExp(`^from ${mod(c).replaceAll('.', '\\.')} import[^\\n]*\\b${fname}\\b`, 'm').test(readFileSync(join(SRC, o), 'utf8'))));
  if (process.env.T4_DRY) { console.log(`${patch}: def=${defFile} cands=${cands.join(',')}`); continue; }
  if (!defFile) throw new Error(`${patch}: no definition file among ${files.join(',')}`);
  sh('git', ['apply', `--include=${defFile}`, p]);
  const before = maps.find((m) => m.path === defFile)!;
  const after = await regionize(defFile, readFileSync(join(SRC, defFile), 'utf8'));
  const d = diffRegions(before.regions, after.regions);
  const changed = [...d.updated, ...d.tombstoned, ...d.renamed.map((r) => r.from)];
  // predicted: reverse BFS ≤ HOPS, keep test-file definitions
  const seen = new Set(changed); let frontier = [...changed];
  for (let h = 0; h < HOPS; h++) { const nxt: string[] = []; for (const x of frontier) for (const y of rev.get(x) ?? []) if (!seen.has(y)) { seen.add(y); nxt.push(y); } frontier = nxt; }
  const predicted = [...seen].filter((id) => { const x = byId.get(id); return x && TEST_PATH.test(x.path) && x.r.kind === 'definition' && /(^|\.)test/.test(x.r.qname); });
  const f = failed(runSuite(join(CACHE, patch + '.txt')));
  for (const b of baseline) f.ids.delete(b);
  const hit = predicted.filter((x) => f.ids.has(x)).length;
  rows.push({ patch, changed, failed: f.ids.size, predicted: predicted.length, hit, crash: f.crash });
  console.log(`${patch}: failed=${f.ids.size} predicted=${predicted.length} hit=${hit}${f.crash ? ' CRASH' : ''}`);
}
sh('git', ['checkout', '-q', '--', '.']);
const use = rows.filter((r) => !r.crash && r.failed > 0);
const F = use.reduce((a, r) => a + r.failed, 0), P = use.reduce((a, r) => a + r.predicted, 0), H = use.reduce((a, r) => a + r.hit, 0);
const recall = F ? H / F : 0;
writeResult('t4', [
  `T4 sample: 36 A patches reduced to their definition-file hunks; full Django suite, serial`,
  `bar: pooled recall ≥ 0.8 at test-method level over patches that break ≥ 1 test`,
  ...rows.map((r) => `  ${r.patch}: changed=${r.changed.length} failed=${r.failed} predicted=${r.predicted} hit=${r.hit}${r.crash ? ' suite_crash' : ''}`),
  `used=${use.length} breaking-nothing=${rows.filter((r) => !r.crash && r.failed === 0).length} crash=${rows.filter((r) => r.crash).length}`,
  `pooled: failed=${F} predicted=${P} hit=${H} recall=${recall.toFixed(3)} precision=${P ? (H / P).toFixed(3) : '—'}`,
  `T4: ${recall >= 0.8 ? 'PASS' : 'FAIL'} (recall ${recall.toFixed(3)})`, ''].join('\n'), rows);
