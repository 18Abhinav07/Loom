import { expect, test } from 'vitest';
import { checkInvariants, regionize } from '../../src/regions/index.js';

const rows = (fr: Awaited<ReturnType<typeof regionize>>) => fr.regions.map((r) => [r.kind, r.qname, fr.text.slice(r.start, r.end)]);

test('json: top-level keys with their trailing comma', async () => {
  const fr = await regionize('cfg/app.json', '{\n  "a": 1,\n  "b": {"c": [1]}\n}\n');
  expect(fr.pack).toBe('json@1');
  expect(rows(fr)).toEqual([
    ['gap', 'gap@start', '{\n  '], ['key', 'a', '"a": 1,'], ['gap', 'gap@after:a', '\n  '],
    ['key', 'b', '"b": {"c": [1]}'], ['gap', 'gap@after:b', '\n}\n'],
  ]);
  expect((await regionize('x.json', '[1,2]\n')).pack).toBe('file');
  expect((await regionize('x.json', '{"a": \n')).pack).toBe('file');
});

test('markdown: flat sections, heading-path names, fences ignored', async () => {
  const md = 'intro\n# A\ntext\n## B\nx\n```\n# not heading\n```\n# C\n';
  expect(rows(await regionize('README.md', md))).toEqual([
    ['gap', 'gap@start', 'intro\n'], ['section', 'A', '# A\ntext\n'],
    ['section', 'A/B', '## B\nx\n```\n# not heading\n```\n'], ['section', 'C', '# C\n'],
  ]);
});

test('whole-file rules: lockfile, generated, minified, >1MB, binary', async () => {
  for (const [path, text, why] of [
    ['pnpm-lock.yaml', 'a: 1\n', 'lockfile'], ['.loom/regions.lock', '{}\n', 'lockfile'],
    ['g.py', '# @generated by tool\ndef f(): pass\n', 'generated'],
    ['m.js', `${'x'.repeat(400)}\n`, 'minified'],
    ['big.py', `${'x = 1\n'.repeat(200_000)}`, 'over 1 MB'],
  ] as const) {
    const fr = await regionize(path, text);
    expect([path, fr.regions.map((r) => r.kind)]).toEqual([path, ['file']]);
    expect(fr.warnings).toContain(`whole-file: ${why}`);
  }
  const bin = await regionize('img.png', Buffer.from([0x89, 0x50, 0xff, 0xfe]));
  expect(bin.binary).toBe(true);
  expect(bin.regions).toHaveLength(1);
});

test('non-ASCII, BOM, CRLF, empty and whitespace-only files keep exact cover (Review Focus 2, 3)', async () => {
  for (const [path, text] of [
    ['u.py', 's = "é😀"\n\ndef f():\n    return "ünï"\n'],
    ['bom.py', '\uFEFFdef f():\n    pass\n'],
    ['crlf.py', 'def f():\r\n    pass\r\n\r\ndef g():\r\n    pass\r\n'],
    ['e.py', ''], ['w.py', '\n\n  \n'], ['e.md', ''],
  ] as const) {
    const fr = await regionize(path, text);
    expect([path, checkInvariants(fr)]).toEqual([path, []]);
  }
  expect((await regionize('crlf.py', 'def f():\r\n    pass\r\n\r\ndef g():\r\n    pass\r\n')).regions.filter((r) => r.kind === 'definition').map((r) => r.qname)).toEqual(['f', 'g']);
  expect((await regionize('e.py', '')).regions).toEqual([]);
});

test('markers: a valid block becomes a section and may split gaps', async () => {
  const src = 'def a():\n    pass\n\n# loom:region setup\nX = 1\nY = 2\n# loom:end\n\ndef b():\n    pass\n';
  const fr = await regionize('m.py', src);
  expect(rows(fr).filter(([k]) => k !== 'gap')).toEqual([
    ['definition', 'a', 'def a():\n    pass\n'],
    ['section', 'setup', '# loom:region setup\nX = 1\nY = 2\n# loom:end\n'],
    ['definition', 'b', 'def b():\n    pass\n'],
  ]);
  expect(fr.warnings).toEqual([]);
  expect(checkInvariants(fr)).toEqual([]);
});

test('markers: cutting a definition, nesting and unbalanced blocks are ignored with warnings; parse stays clean', async () => {
  const cut = await regionize('c.py', 'def a():\n    # loom:region x\n    pass\n# loom:end\n');
  expect(cut.degraded).toBe(false);
  expect(cut.regions.some((r) => r.kind === 'section')).toBe(false);
  expect(cut.warnings).toEqual(['marker: x cuts definition a; ignored']);
  const nested = await regionize('n.py', '# loom:region o\n# loom:region i\nX = 1\n# loom:end\n# loom:end\n');
  expect(nested.regions.some((r) => r.kind === 'section')).toBe(false);
  expect(nested.warnings.length).toBeGreaterThanOrEqual(2);
  const open = await regionize('u.py', '# loom:region o\nX = 1\n');
  expect(open.warnings).toEqual(['marker: unclosed loom:region o at line 1']);
  const md = await regionize('r.md', '# A\n<!-- loom:region keep -->\nx\n<!-- loom:end -->\n');
  expect(md.warnings[0]).toMatch(/keep cuts section A/);
  const yaml = await regionize('c.yaml', 'a: 1\n# loom:region db\nb: 2\n# loom:end\n');
  expect(rows(yaml).map(([k, q]) => `${k}:${q}`)).toEqual(['gap:gap@start', 'section:db']);
});

test('agent-defined regions apply only to files with no pack, and are validated', async () => {
  const text = 'line1\nline2\nline3\n';
  const ok = await regionize('notes.txt', text, { defined: [{ start: 6, end: 12, name: 'mid' }] });
  expect(rows(ok)).toEqual([['gap', 'gap@start', 'line1\n'], ['section', 'mid', 'line2\n'], ['gap', 'gap@after:mid', 'line3\n']]);
  const bad = await regionize('notes.txt', text, { defined: [{ start: 0, end: 8, name: 'a' }, { start: 6, end: 12, name: 'b' }] });
  expect(bad.pack).toBe('file');
  expect(bad.warnings[0]).toMatch(/^defined: /);
  const py = await regionize('p.py', 'X = 1\n', { defined: [{ start: 0, end: 6, name: 'z' }] });
  expect(py.regions.map((r) => r.qname)).toEqual(['X']);
});
